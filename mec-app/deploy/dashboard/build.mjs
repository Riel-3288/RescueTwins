import { build } from 'esbuild';
import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';

const root = fileURLToPath(new URL('.', import.meta.url));
await build({
  absWorkingDir: root, entryPoints: ['src/main.js'], outfile: 'app.js',
  bundle: true, format: 'iife', target: ['es2022'], minify: true,
  legalComments: 'inline', banner: {js: '/* Generated by npm run build. Edit dashboard/src/ instead. */'}
});
await writeFile(new URL('THIRD-PARTY-LICENSES.txt', import.meta.url),
  'Three.js 0.180.0 — https://github.com/mrdoob/three.js\n\n' +
  await readFile(new URL('node_modules/three/LICENSE', import.meta.url), 'utf8'));
console.log('Built dashboard/app.js. Python serves this bundle without Node or a CDN.');
